"""
Keep literal secrets out of `.env.dev`.

`.env.dev` is public, and whatever it holds ends up in every developer's `.env` and, sooner or later,
on a server. So it carries no secret of its own: `setup-env.sh` generates them when it turns the file
into `.env`. Two rules hold that in place:

  1. A variable that `.env.prod` fills from a generated placeholder (REPLACE_WITH_RANDOM_STRING,
     REPLACE_WITH_64_HEX_CHARS, ...) holds the very same value in `.env.dev`.
  2. Any other variable named like a secret (`*_KEY`, `*_SECRET`, `*_TOKEN`, `*_PASSWORD`, `*_PASS`)
     is empty, the `XXX` stand-in for a credential the developer brings, or a `${VAR}` reference to
     a generated one. `*_ACCESS_KEY` names an S3 user, not a secret, and is exempt.
"""

import re
from pathlib import Path

from env_inventory import format_repo_path

_ASSIGNMENT_RE = re.compile(r"^([A-Z_][A-Z0-9_]*)=(.*)$")
_GENERATED_PLACEHOLDER_RE = re.compile(r"REPLACE_WITH_(RANDOM_STRING|64_HEX_CHARS|RANDOM_UUID|FERNET_KEY|LANGFUSE_)")
_SECRET_NAME_RE = re.compile(r"_(KEY|SECRET|TOKEN|PASSWORD|PASS)$")
_NOT_SECRET_NAME_RE = re.compile(r"_ACCESS_KEY$")
_ALLOWED_SECRET_VALUES = {"", "XXX"}


def check_dev_env_secrets(dev_env_file: Path, prod_env_file: Path) -> bool:
    """Report every literal secret in the dev env file. Returns True if there is none."""
    dev = _read_env_values(dev_env_file)
    generated_in_prod = {
        name: value
        for name, value in _read_env_values(prod_env_file).items()
        if _GENERATED_PLACEHOLDER_RE.search(value)
    }

    errors = [
        f"{name:45s} must be {generated_in_prod[name]!r} as in {prod_env_file.name}, setup-env.sh generates it"
        for name in sorted(generated_in_prod.keys() & dev.keys())
        if dev[name] != generated_in_prod[name]
    ]
    errors += [
        f"{name:45s} holds a literal secret; leave it empty or reference a generated one as '${{VAR}}'"
        for name, value in sorted(dev.items())
        if name not in generated_in_prod and _is_literal_secret(name, value)
    ]

    print(f"\n  Dev env secret check ({format_repo_path(dev_env_file)})")
    if errors:
        print(f"    ERROR ({len(errors)}):")
        for error in errors:
            print(f"      - {error}")
    else:
        print(f"    OK: no literal secrets, {len(generated_in_prod)} generated by setup-env.sh")
    return not errors


def _is_literal_secret(name: str, value: str) -> bool:
    if not _SECRET_NAME_RE.search(name) or _NOT_SECRET_NAME_RE.search(name):
        return False
    return value not in _ALLOWED_SECRET_VALUES and "${" not in value


def _read_env_values(path: Path) -> dict[str, str]:
    """Variable values of an env file, with the surrounding quotes removed."""
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _ASSIGNMENT_RE.match(line.strip())
        if match:
            values[match.group(1)] = _unquote(match.group(2).strip())
    return values


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value
