    # A label may carry a short number ("Position 2", "Art. 5", "Nr. 12a"); four digits at most, so no ID or phone fits.
    NUMBERED_LABEL_SUFFIX: ClassVar[str] = r"(?:\s*(?:Nr\.?|No\.?|n°)?\s*\d{1,4}[a-z]?)?"

    @classmethod
    def allow_list_pattern(cls) -> str:
        """One pattern a span must match in full to stay unmasked. String anchors, not ^ and $: the analyzer matches
        with MULTILINE, so ^ and $ would let a span over a line break pass on its first line."""
        alternation = "|".join(re.escape(word) for word in cls.ALLOW_LIST)
        return rf"\A(?:{alternation}){cls.NUMBERED_LABEL_SUFFIX}\Z"
